import AppKit
import SwiftUI

/// Device icons: the picker's symbol list, how each symbol is drawn, and the
/// PNG files Core Audio hands out as device icons (kAudioDevicePropertyIcon
/// is a file URL). The files live in /Users/Shared so every process that
/// shows device icons can read them.
///
/// Icons are drawn two-tone (hierarchical). A symbol uses its filled variant
/// only when that variant really has two tones; otherwise it stays outlined.
enum IconRenderer {
    static let directory = URL(fileURLWithPath: "/Users/Shared/SimpleAudioManager/Icons", isDirectory: true)

    struct SymbolGroup: Identifiable {
        let title: String
        let symbols: [String]
        var id: String { title }
    }

    /// Curated symbols for the icon picker, one row per kind of device.
    /// Symbols this macOS version lacks are left out.
    static let symbolGroups: [SymbolGroup] = [
        SymbolGroup(title: "Speakers", symbols: [
            "hifispeaker", "hifispeaker.2", "soundbar", "homepod", "homepod.2",
            "homepod.mini", "speaker.wave.2", "amplifier", "hifireceiver", "radio",
        ]),
        SymbolGroup(title: "Headphones and Headsets", symbols: [
            "headphones", "headset", "earbuds", "earpods", "airpods", "airpods.pro", "airpods.max",
        ]),
        SymbolGroup(title: "Screens", symbols: [
            "tv", "display", "display.2", "videoprojector",
        ]),
        SymbolGroup(title: "Microphones, Cameras and Speakerphones", symbols: [
            "mic", "music.mic", "desk.microphone", "waveform.and.mic", "speakerphone", "webcam", "mirrorless.camera",
        ]),
        SymbolGroup(title: "Computers and Devices", symbols: [
            "laptopcomputer", "desktopcomputer", "iphone", "ipad",
        ]),
        SymbolGroup(title: "Other", symbols: [
            "airplayaudio", "cable.coaxial", "cable.connector", "antenna.radiowaves.left.and.right",
            "slider.vertical.3", "waveform", "music.note", "guitars", "pianokeys",
        ]),
    ].compactMap { group in
        let available = group.symbols.filter { symbolImage($0) != nil }
        return available.isEmpty ? nil : SymbolGroup(title: group.title, symbols: available)
    }

    static var symbols: [String] { symbolGroups.flatMap(\.symbols) }

    /// Symbols drawn for this app (asset catalog, generated by
    /// Scripts/render-symbols.py), not part of SF Symbols.
    static let customSymbols: Set<String> = [
        "soundbar", "webcam", "mirrorless.camera", "desk.microphone", "speakerphone",
        "mic.twotone", "music.mic.twotone",
    ]

    /// SF Symbols whose filled variant has only one tone, replaced by the
    /// app's two-tone drawing. The stored name stays the SF Symbol's.
    private static let twoToneReplacements = [
        "mic": "mic.twotone",
        "music.mic": "music.mic.twotone",
    ]

    /// SF Symbols whose ".fill" variant is two-tone. All others are drawn
    /// outlined: their fills are a single solid tone.
    private static let twoToneFills: Set<String> = [
        "hifispeaker", "hifispeaker.2", "homepod", "homepod.2", "homepod.mini",
        "speaker.wave.2", "guitars", "square.stack.3d.up",
    ]

    /// Bump when drawings or the badge change: icon files get new names, so
    /// they are rendered again and Core Audio clients reload them.
    static let iconRevision = 3

    /// What is drawn for a stored symbol name.
    static func drawnSymbol(_ name: String) -> (name: String, isCustom: Bool) {
        let name = twoToneReplacements[name] ?? name
        if customSymbols.contains(name) {
            return (name, true)
        }
        return (twoToneFills.contains(name) ? name + ".fill" : name, false)
    }

    /// The symbol as an NSImage, from SF Symbols or the app's own symbols.
    static func symbolImage(_ name: String) -> NSImage? {
        let drawn = drawnSymbol(name)
        if drawn.isCustom {
            return NSImage(symbolName: drawn.name, bundle: .main, variableValue: 1)
        }
        return NSImage(systemSymbolName: drawn.name, accessibilityDescription: nil)
    }

    /// Returns the icon file for a symbol, rendering it on first use.
    static func iconURL(for symbol: String) -> URL? {
        let url = directory.appending(path: "\(symbol)-r\(iconRevision).png")
        if FileManager.default.fileExists(atPath: url.path) {
            return url
        }
        guard let data = render(symbol: symbol) else { return nil }
        do {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            try data.write(to: url, options: .atomic)
            return url
        } catch {
            return nil
        }
    }

    /// Deletes icon files from older revisions that no proxy points at.
    static func removeStaleIcons(keeping inUse: Set<URL>) {
        let keep = Set(inUse.map(\.lastPathComponent))
        let current = "-r\(iconRevision).png"
        let files = (try? FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)) ?? []
        for file in files where file.pathExtension == "png"
            && !file.lastPathComponent.hasSuffix(current) && !keep.contains(file.lastPathComponent) {
            try? FileManager.default.removeItem(at: file)
        }
    }

    /// A neutral round badge with the white two-tone glyph, like macOS
    /// device icons. Drawn with SwiftUI so it matches the app's icons.
    private static func render(symbol: String, size: CGFloat = 512) -> Data? {
        guard symbolImage(symbol) != nil else { return nil }
        let badge = ZStack {
            Circle()
                .inset(by: size * 0.04)
                .fill(LinearGradient(colors: [Color(white: 0.55), Color(white: 0.32)], startPoint: .top, endPoint: .bottom))
            Image(deviceSymbol: symbol)
                .font(.system(size: size * 0.42, weight: .medium))
                .foregroundStyle(.white)
        }
        .frame(width: size, height: size)
        let renderer = ImageRenderer(content: badge)
        renderer.scale = 1
        guard let image = renderer.cgImage else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }
}

extension Image {
    /// A device symbol, drawn two-tone: SF Symbol or one of the app's own.
    init(deviceSymbol name: String) {
        let drawn = IconRenderer.drawnSymbol(name)
        let image = drawn.isCustom ? Image(drawn.name) : Image(systemName: drawn.name)
        self = image.symbolRenderingMode(.hierarchical)
    }
}
